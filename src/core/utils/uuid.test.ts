import { describe, expect, it } from "vitest";
import { isUuid } from "./uuid";

describe("isUuid", () => {
  it.each([
    "11111111-1111-1111-8111-111111111111",
    "22222222-2222-2222-8222-222222222222",
    "33333333-3333-3333-8333-333333333333",
    "22222222-2222-4222-9222-222222222222",
    "55555555-5555-5555-a555-555555555555",
    "66666666-6666-6666-a666-666666666666",
    "77777777-7777-7777-a777-777777777777",
    "88888888-8888-8888-b888-888888888888",
    "AAAAAAAA-AAAA-4AAA-8AAA-AAAAAAAAAAAA",
  ])("accepts RFC UUID %s", (value) => {
    expect(isUuid(value)).toBe(true);
  });

  it.each([
    "00000000-0000-4000-7000-000000000000",
    "99999999-9999-9999-8999-999999999999",
    "11111111-1111-0111-8111-111111111111",
    "11111111-1111-9111-8111-111111111111",
    "11111111-1111-4111-0111-111111111111",
    "11111111-1111-4111-c111-111111111111",
    "111111111111-4111-8111-111111111111",
  ])("rejects non-RFC UUID %s", (value) => {
    expect(isUuid(value)).toBe(false);
  });

  it("rejects non-string input", () => {
    expect(isUuid(null)).toBe(false);
    expect(isUuid(42)).toBe(false);
  });
});
